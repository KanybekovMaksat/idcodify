function fill(template: string, name: string, gender: Gender): string {
  return template
    .replace(/\{name\}/g, name)
    .replace(/\{([^{}|]*)\|([^{}|]*)\}/g, (_, m: string, f: string) => (gender === 'f' ? f : m));
}

/** Текст карты для архетипа, подставив имя и род. null, если архетип неизвестен. */
export function archetypeCard(id: string, name: string, gender: Gender): CardText | null {
  const card = CARDS[id];
  if (!card) return null;
  return {
    title: card.title,
    portrait: fill(card.portrait, name, gender),
    strengths: card.strengths.map((s) => fill(s, name, gender)),
    fits: card.fits,
  };
}
